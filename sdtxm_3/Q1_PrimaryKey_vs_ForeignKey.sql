-- Q1: Explain the difference between Primary Key and Foreign Key in SQL.

-- Primary Key:
-- 1) Uniquely identifies each row in a table.
-- 2) Must be UNIQUE and NOT NULL.
-- 3) One primary key per table (can be composite).

-- Foreign Key:
-- 1) A column that references a primary key in another table.
-- 2) Enforces referential integrity between tables.
-- 3) Can contain duplicate values and may be NULL (if allowed).
